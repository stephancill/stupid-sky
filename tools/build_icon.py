#!/usr/bin/env python3
"""
Builds the stupid sky app icon (black mark on white) from the 24x24 loop icon (tools/loop-icon.svg).

Android VectorDrawables can't do dash arrays or masks, so the geometry is computed here:
the first half of the curve is cut out exactly (de Casteljau split), the dots of the second
half become circles at evenly spaced lengths, and the midpoint becomes a filled dot.

    python3 tools/build_icon.py

Writes the launcher foreground, the notification icon, and a preview SVG.
"""
import math
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "tools", "loop-icon.svg")
RES = os.path.join(ROOT, "app", "src", "main", "res")

# Stroke sizes in the 24-unit icon grid (same as the SVG).
SOLID_W = 2.0
DOT_R = 0.9
CENTRE_R = 2.25
DOT_STEP = 0.05          # dots every 5% of the path length (matches dasharray "0 50" of 1000)

d = re.search(r'id="loop"[^>]*\sd="([^"]+)"', open(SRC).read()).group(1)
n = list(map(float, re.findall(r"-?\d+\.?\d*", d)))
segs, cur, i = [], (n[0], n[1]), 2
while i < len(n):
    seg = (cur, (n[i], n[i + 1]), (n[i + 2], n[i + 3]), (n[i + 4], n[i + 5]))
    segs.append(seg)
    cur = seg[3]
    i += 6


def bez(s, t):
    a, b, c, e = s
    u = 1 - t
    return (u ** 3 * a[0] + 3 * u * u * t * b[0] + 3 * u * t * t * c[0] + t ** 3 * e[0],
            u ** 3 * a[1] + 3 * u * u * t * b[1] + 3 * u * t * t * c[1] + t ** 3 * e[1])


# Arc-length table: (cumulative length, segment index, t)
table, total = [(0.0, 0, 0.0)], 0.0
for si, s in enumerate(segs):
    prev = s[0]
    for k in range(1, 401):
        t = k / 400
        p = bez(s, t)
        total += math.dist(prev, p)
        prev = p
        table.append((total, si, t))


def at(length):
    """(segment index, t) at a distance along the path."""
    for j in range(1, len(table)):
        if table[j][0] >= length:
            l0, s0, t0 = table[j - 1]
            l1, s1, t1 = table[j]
            if s0 != s1:
                t0 = 0.0
            f = (length - l0) / (l1 - l0) if l1 > l0 else 0
            return s1, t0 + (t1 - t0) * f
    return len(segs) - 1, 1.0


def point(length):
    si, t = at(length)
    return bez(segs[si], t)


def split(s, t):
    """Left part of a cubic split at t (de Casteljau)."""
    a, b, c, e = s
    lerp = lambda p, q: (p[0] + (q[0] - p[0]) * t, p[1] + (q[1] - p[1]) * t)
    ab, bc, ce = lerp(a, b), lerp(b, c), lerp(c, e)
    abc, bce = lerp(ab, bc), lerp(bc, ce)
    return (a, ab, abc, lerp(abc, bce))


mid_seg, mid_t = at(total / 2)
first_half = segs[:mid_seg] + [split(segs[mid_seg], mid_t)]
centre = point(total / 2)
dots = [point(total * (0.5 + DOT_STEP * k)) for k in range(1, round(0.5 / DOT_STEP) + 1)]


def f(v):
    return f"{v:.3f}".rstrip("0").rstrip(".")


def geometry(scale, ox, oy):
    """Path data (in a target grid) for the solid curve and for all filled circles."""
    tr = lambda p: (p[0] * scale + ox, p[1] * scale + oy)
    p0 = tr(first_half[0][0])
    curve = [f"M{f(p0[0])},{f(p0[1])}"]
    for s in first_half:
        b, c, e = tr(s[1]), tr(s[2]), tr(s[3])
        curve.append(f"C{f(b[0])},{f(b[1])} {f(c[0])},{f(c[1])} {f(e[0])},{f(e[1])}")

    def circle(p, r):
        x, y = tr(p)
        r *= scale
        return f"M{f(x - r)},{f(y)}a{f(r)},{f(r)} 0 1,0 {f(2 * r)},0a{f(r)},{f(r)} 0 1,0 {f(-2 * r)},0"

    circles = "".join(circle(p, DOT_R) for p in dots) + circle(centre, CENTRE_R)
    return " ".join(curve), circles, SOLID_W * scale


def vector(size, viewport, scale, ox, oy, color, extra=""):
    curve, circles, w = geometry(scale, ox, oy)
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/build_icon.py from tools/loop-icon.svg. Do not edit by hand. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{size}dp"
    android:height="{size}dp"
    android:viewportWidth="{viewport}"
    android:viewportHeight="{viewport}"{extra}>
    <path
        android:pathData="{curve}"
        android:strokeColor="{color}"
        android:strokeWidth="{f(w)}"
        android:strokeLineCap="round"
        android:strokeLineJoin="round" />
    <path
        android:pathData="{circles}"
        android:fillColor="{color}" />
</vector>
'''


# Adaptive icon: 108dp canvas, keep the mark inside the 66dp safe zone (scale 2.4 -> ~58dp).
FG_SCALE = 2.4
FG_OFF = (108 - 24 * FG_SCALE) / 2
with open(os.path.join(RES, "drawable", "ic_launcher_foreground.xml"), "w") as fh:
    fh.write(vector(108, 108, FG_SCALE, FG_OFF, FG_OFF, "#FF000000"))
# Themed (monochrome) icon for Android 13+: same mark, the system tints it.
with open(os.path.join(RES, "drawable", "ic_launcher_monochrome.xml"), "w") as fh:
    fh.write(vector(108, 108, FG_SCALE, FG_OFF, FG_OFF, "#FFFFFFFF"))
# Notification icon: 24dp, white on transparent.
with open(os.path.join(RES, "drawable", "ic_stat_logo.xml"), "w") as fh:
    fh.write(vector(24, 24, 1, 0, 0, "#FFFFFFFF"))

# Preview: the launcher icon as Android masks it (circle and squircle), plus the notification icon.
curve, circles, w = geometry(FG_SCALE, FG_OFF, FG_OFF)
bg = ''
mark = f'<path d="{curve}" fill="none" stroke="#000" stroke-width="{f(w)}" stroke-linecap="round" stroke-linejoin="round"/><path d="{circles}" fill="#000"/>'
open(os.path.join(ROOT, "tools", "icon-preview.svg"), "w").write(
    f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108">{bg}<rect width="108" height="108" fill="#fff"/>{mark}</svg>\n')
print(f"path length {total:.2f}; centre {centre[0]:.2f},{centre[1]:.2f}; {len(dots)} dots")
